import AppKit
import Carbon.HIToolbox

/// macOS virtual key codes -> PC set-1 scancodes (0x100 = E0 prefix). Scancodes are positional, so
/// the Windows keyboard layout (e.g. Italian) decides the character, like a real PC keyboard.
enum KeyMap {
    private static let table: [UInt16: UInt16] = [
        0x00: 0x1E, 0x01: 0x1F, 0x02: 0x20, 0x03: 0x21, 0x04: 0x23, 0x05: 0x22, 0x06: 0x2C, 0x07: 0x2D,
        0x08: 0x2E, 0x09: 0x2F, 0x0B: 0x30, 0x0C: 0x10, 0x0D: 0x11, 0x0E: 0x12, 0x0F: 0x13, 0x10: 0x15,
        0x11: 0x14, 0x12: 0x02, 0x13: 0x03, 0x14: 0x04, 0x15: 0x05, 0x16: 0x07, 0x17: 0x06, 0x18: 0x0D,
        0x19: 0x0A, 0x1A: 0x08, 0x1B: 0x0C, 0x1C: 0x09, 0x1D: 0x0B, 0x1E: 0x1B, 0x1F: 0x18, 0x20: 0x16,
        0x21: 0x1A, 0x22: 0x17, 0x23: 0x19, 0x24: 0x1C, 0x25: 0x26, 0x26: 0x24, 0x27: 0x28, 0x28: 0x25,
        0x29: 0x27, 0x2A: 0x2B, 0x2B: 0x33, 0x2C: 0x35, 0x2D: 0x31, 0x2E: 0x32, 0x2F: 0x34, 0x30: 0x0F,
        0x31: 0x39, 0x33: 0x0E, 0x35: 0x01,
        // Keypad
        0x41: 0x53, 0x43: 0x37, 0x45: 0x4E, 0x47: 0x45, 0x4B: 0x135, 0x4C: 0x11C, 0x4E: 0x4A, 0x51: 0x59,
        0x52: 0x52, 0x53: 0x4F, 0x54: 0x50, 0x55: 0x51, 0x56: 0x4B, 0x57: 0x4C, 0x58: 0x4D, 0x59: 0x47,
        0x5B: 0x48, 0x5C: 0x49,
        // Function keys (F13 = Print Screen, F14 = Scroll Lock)
        0x7A: 0x3B, 0x78: 0x3C, 0x63: 0x3D, 0x76: 0x3E, 0x60: 0x3F, 0x61: 0x40, 0x62: 0x41, 0x64: 0x42,
        0x65: 0x43, 0x6D: 0x44, 0x67: 0x57, 0x6F: 0x58, 0x69: 0x137, 0x6B: 0x46,
        // Navigation
        0x72: 0x152, 0x73: 0x147, 0x74: 0x149, 0x75: 0x153, 0x77: 0x14F, 0x79: 0x151,
        0x7B: 0x14B, 0x7C: 0x14D, 0x7D: 0x150, 0x7E: 0x148,
        // Media: mute, volume down, volume up
        0x4A: 0x120, 0x49: 0x12E, 0x48: 0x130,
    ]

    /// ISO keyboards (Italian Macs) have an extra key next to left Shift; macOS reports the two
    /// keys around it swapped compared with ANSI.
    private static let isISO: Bool = Int(KBGetLayoutType(Int16(LMGetKbdType()))) == Int(kKeyboardISO)

    static func scancode(forKeyCode code: UInt16) -> UInt16? {
        switch code {
        case 0x0A: return 0x29                    // § / key left of 1 on ISO
        case 0x32: return isISO ? 0x56 : 0x29     // < > on ISO, ` on ANSI
        default: return table[code]
        }
    }

    struct Modifier {
        let scancode: UInt16
        let deviceMask: UInt
    }

    /// Modifier keys arrive as flagsChanged; the device-dependent bits tell left from right.
    static func modifier(forKeyCode code: UInt16, commandAsControl: Bool) -> Modifier? {
        switch code {
        case 0x38: return Modifier(scancode: 0x2A, deviceMask: 0x02)       // left shift
        case 0x3C: return Modifier(scancode: 0x36, deviceMask: 0x04)       // right shift
        // With ⌘ as Ctrl, the left ⌃ becomes the Windows key (Start menu, Win+Shift+S, Win+E…).
        case 0x3B: return Modifier(scancode: commandAsControl ? 0x15B : 0x1D, deviceMask: 0x01) // left control
        case 0x3E: return Modifier(scancode: 0x11D, deviceMask: 0x2000)    // right control
        case 0x3A: return Modifier(scancode: 0x38, deviceMask: 0x20)       // left option -> Alt
        case 0x3D: return Modifier(scancode: 0x138, deviceMask: 0x40)      // right option -> AltGr
        case 0x37: return Modifier(scancode: commandAsControl ? 0x1D : 0x15B, deviceMask: 0x08)  // left cmd
        case 0x36: return Modifier(scancode: commandAsControl ? 0x11D : 0x15C, deviceMask: 0x10) // right cmd
        default: return nil
        }
    }

    static let capsLockKeyCode: UInt16 = 0x39
    static let capsLockScancode: UInt16 = 0x3A
}
